#!/usr/bin/env python3
"""PRO-152: анализ парных A/B-прогонов tests/strains_ab.sh.

python tests/strains_ab.py <каталог прогонов> <каталог вывода>

Пары — одинаковые (сид, семейство карты) в двух плечах одной ячейки. Метрики считаются на всех партиях (intention-to-treat):
партия, проигранная раньше окна, получает худший исход по пропущенным волнам. Окно M1 — волны 6–15 без боссовой 10-й.
ДИ — бутстреп 95% по парам (2000 повторов, фиксированный сид генератора).
Пишет ab_tables.md (таблицы для docs) и ab_pairs.csv (по строке на пару и сравнение).
"""
import csv
import glob
import json
import os
import random
import sys
from collections import defaultdict

WINDOW = [w for w in range(6, 16) if w != 10]
PACKS = ["brood", "hulk", "flock"]
COUNTER_TOWERS = {"cannon", "tesla", "ember", "poison", "flak"}


def load(d):
    runs = defaultdict(dict)  # (cell, arm) -> {(seed, fam): run}
    for f in glob.glob(os.path.join(d, "*.jsonl")):
        name = os.path.basename(f)[:-6]
        cell, fam, arm = name.rsplit("_", 2)
        for line in open(f, encoding="utf-8"):
            r = json.loads(line)
            runs[(cell, arm)][(r["seed"], r["family"])] = r
    return runs


def waves_by_no(r):
    return {w["w"]: w for w in r["waves"]}


def window_lives(r):
    """Жизни, потерянные на небоссовых волнах окна (проигранная волна — все оставшиеся жизни, после поражения — 0)."""
    wb = waves_by_no(r)
    lost = 0
    for w in WINDOW:
        x = wb.get(w)
        if x is None:
            continue
        if x.get("lost"):
            lost += int(x.get("lives0", 0))
        else:
            lost += int(x.get("lives_lost", 0))
    return lost


def window_p90(r):
    """Средний p90 дистанции гибели наземных врагов по окну; волны после поражения — 1.5 (прорыв)."""
    wb = waves_by_no(r)
    vals = []
    for w in WINDOW:
        x = wb.get(w)
        if x is None or x.get("lost") or "prog_g" not in x or x["prog_g"][2] == 0:
            vals.append(1.5)
        else:
            vals.append(float(x["prog_g"][1]))
    return sum(vals) / len(vals)


def window_hp(r):
    wb = waves_by_no(r)
    return sum(int(wb[w]["sx"]["wave_hp"]) for w in WINDOW if w in wb and "sx" in wb[w])


def won(r):
    return 1.0 if r["summary"]["end_wave"] > 30 else 0.0


def end_wave(r):
    return float(min(r["summary"]["end_wave"], 31))


def lives30(r):
    return float(max(0, r["summary"]["final_lives"])) if r["summary"]["end_wave"] > 30 else 0.0


def first_wave(r, pred):
    for x in r["waves"]:
        sx = x.get("sx")
        if sx and pred(sx):
            return x["w"]
    return None


def strain_share(r, p):
    """Средняя доля пакета p в волнах окна (по размеченным геномам)."""
    wb = waves_by_no(r)
    v = []
    for w in WINDOW:
        x = wb.get(w)
        if x and "sx" in x:
            v.append(x["sx"]["strain_n"].get(p, 0) / max(1, x["size"]) if "size" in x else 0.0)
    return sum(v) / len(v) if v else 0.0


def counter_built(r):
    comp = r["summary"]["composition"]
    return sum(comp.get(k, 0) for k in COUNTER_TOWERS)


def boot(diffs, n=2000, seed=152):
    if not diffs:
        return (float("nan"),) * 3
    rnd = random.Random(seed)
    m = sum(diffs) / len(diffs)
    means = []
    for _ in range(n):
        s = [diffs[rnd.randrange(len(diffs))] for _ in diffs]
        means.append(sum(s) / len(s))
    means.sort()
    return m, means[int(0.025 * n)], means[int(0.975 * n) - 1]


def fmt(t, d=2):
    m, lo, hi = t
    return f"{m:+.{d}f} [{lo:+.{d}f}; {hi:+.{d}f}]"


METRICS = [
    ("жизни −, окно", window_lives, 2),
    ("p90 гибели, окно", window_p90, 3),
    ("побед 30", won, 2),
    ("конец, волна", end_wave, 1),
    ("жизни к 30", lives30, 1),
]


def paired(a, b, fn):
    keys = sorted(set(a) & set(b))
    return [fn(b[k]) - fn(a[k]) for k in keys], keys


def mean(xs):
    return sum(xs) / len(xs) if xs else float("nan")


def main():
    src, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    runs = load(src)
    cells = sorted({c for c, _ in runs})
    lines = ["<!-- generated by tests/strains_ab.py -->", ""]
    rows_csv = []

    # 1. Плечо A: давление (A1 − A0) и замороженная политика (F1 − F0)
    lines += ["### Давление: A1 − A0 (живой бот) и F1 − F0 (замороженная политика)", "",
              "| ячейка | сравнение | n | " + " | ".join(m[0] for m in METRICS) + " | HP волн окна, ON/OFF | побед OFF → ON |",
              "|---|---|---|" + "---|" * len(METRICS) + "---|---|"]
    for cell in cells:
        for a0, a1 in [("A0", "A1"), ("F0", "F1")]:
            A, B = runs.get((cell, a0)), runs.get((cell, a1))
            if not A or not B:
                continue
            cols = []
            n = 0
            for label, fn, dg in METRICS:
                diffs, keys = paired(A, B, fn)
                n = len(keys)
                cols.append(fmt(boot(diffs), dg))
                for k, dv in zip(keys, diffs):
                    rows_csv.append([cell, f"{a1}-{a0}", k[0], k[1], label, round(dv, 4)])
            keys = sorted(set(A) & set(B))
            hp0 = sum(window_hp(A[k]) for k in keys)
            hp1 = sum(window_hp(B[k]) for k in keys)
            w0 = mean([won(A[k]) for k in keys])
            w1 = mean([won(B[k]) for k in keys])
            lines.append(f"| {cell} | {a1}−{a0} | {n} | " + " | ".join(cols) + f" | {hp1 / hp0 if hp0 else float('nan'):.3f} | {w0:.0%} → {w1:.0%} |")
    lines.append("")

    # 2. M-D: необходимость решения
    lines += ["### Необходимость решения: (B1 − A1) − (B0 − A0)", "",
              "B — бот строит ответ из таблицы контрходов, когда рой объявляет пакет. Положительное M-D по жизням/победам — контрход окупается именно под флагом.", "",
              "| ячейка | n | B1−A1 жизни окна | B0−A0 жизни окна | **M-D жизни окна** | B1−A1 побед | B0−A0 побед | **M-D побед** | M-D жизни к 30 |",
              "|---|---|---|---|---|---|---|---|---|"]
    for cell in cells:
        A0, A1, B0, B1 = (runs.get((cell, x)) for x in ("A0", "A1", "B0", "B1"))
        if not (A0 and A1 and B0 and B1):
            continue
        keys = sorted(set(A0) & set(A1) & set(B0) & set(B1))
        def dd(fn, sign=1):
            on = [sign * (fn(B1[k]) - fn(A1[k])) for k in keys]
            off = [sign * (fn(B0[k]) - fn(A0[k])) for k in keys]
            md = [x - y for x, y in zip(on, off)]
            return boot(on), boot(off), boot(md)
        lon, loff, lmd = dd(window_lives, -1)  # меньше потерь = лучше, поэтому знак −
        won_on, won_off, won_md = dd(won)
        _, _, l30 = dd(lives30)
        lines.append(f"| {cell} | {len(keys)} | {fmt(lon)} | {fmt(loff)} | **{fmt(lmd)}** | {fmt(won_on)} | {fmt(won_off)} | **{fmt(won_md)}** | {fmt(l30, 1)} |")
    lines.append("")
    lines.append("Знак жизней окна в этой таблице: + = контрход сберёг жизни.")
    lines.append("")

    # 3. Ответ роя: когда и чем
    lines += ["### Ответ роя (плечо A1): первый анонс / первое появление, средняя доля в окне 6–15", "",
              "| ячейка | n | " + " | ".join(f"{p}: анонс · появление · доля" for p in PACKS) + " | C (волна 10) | burst / chill / небо (волна 10) |",
              "|---|---|" + "---|" * len(PACKS) + "---|---|"]
    for cell in cells:
        R = runs.get((cell, "A1"))
        if not R:
            continue
        cols = []
        for p in PACKS:
            ann = [first_wave(r, lambda sx, p=p: sx["pk"][p][2] == "announced") for r in R.values()]
            act = [first_wave(r, lambda sx, p=p: sx["pk"][p][2] == "active") for r in R.values()]
            ann_v = sorted(x for x in ann if x)
            act_v = sorted(x for x in act if x)
            med = lambda v: v[len(v) // 2] if v else "—"
            share = mean([strain_share(r, p) for r in R.values()])
            cols.append(f"{len(ann_v)}/{len(R)}: {med(ann_v)} · {med(act_v)} · {share:.0%}")
        c10, sig10 = [], []
        for r in R.values():
            x = waves_by_no(r).get(10)
            if x and "sx" in x:
                c10.append(x["sx"]["C"])
                sig10.append((x["sx"]["burst"], x["sx"]["chill"], x["sx"]["air_gap"]))
        b = mean([s[0] for s in sig10]); ch = mean([s[1] for s in sig10]); ag = mean([s[2] for s in sig10])
        lines.append(f"| {cell} | {len(R)} | " + " | ".join(cols) + f" | {mean(c10):.2f} | {b:.2f} / {ch:.2f} / {ag:.2f} |")
    lines.append("")

    # 4. Утечки по типам врагов (A1) и экономика
    lines += ["### Утечки и экономика (сумма по партиям ячейки, волны 1–30)", "",
              "| ячейка | плечо | утечки обычных | выводок | панцирники | стая | золото за убийства | вложено к концу | ответных башен |",
              "|---|---|---|---|---|---|---|---|---|"]
    for cell in cells:
        for arm in ("A0", "A1", "B0", "B1"):
            R = runs.get((cell, arm))
            if not R:
                continue
            lk = defaultdict(int)
            inc = 0
            inv = []
            cb = []
            for r in R.values():
                for x in r["waves"]:
                    for p in ["base"] + PACKS:
                        lk[p] += int(x.get("leak_" + p, 0))
                    inc += int(x.get("kill_income", 0))
                inv.append(r["waves"][-1].get("invested", 0) if r["waves"] else 0)
                cb.append(counter_built(r))
            lines.append(f"| {cell} | {arm} | {lk['base']} | {lk['brood']} | {lk['hulk']} | {lk['flock']} | {inc} | {mean(inv):.0f} | {mean(cb):.1f} |")
    lines.append("")

    # 5. Смена обороны (switch): когда пакет начал уходить
    R = runs.get(("switch_normal", "A1"))
    if R:
        lines += ["### Смена обороны на 13-й волне (switch, A1): доли пакетов по волнам (среднее по партиям)", "",
                  "| волна | " + " | ".join(PACKS) + " | burst | chill |", "|---|" + "---|" * (len(PACKS) + 2)]
        for w in range(8, 26):
            sh = {p: [] for p in PACKS}
            bc = []
            for r in R.values():
                x = waves_by_no(r).get(w)
                if x and "sx" in x:
                    for p in PACKS:
                        sh[p].append(x["sx"]["pk"][p][1])
                    bc.append((x["sx"]["burst"], x["sx"]["chill"]))
            if bc:
                lines.append(f"| {w} | " + " | ".join(f"{mean(sh[p]):.2f}" for p in PACKS) + f" | {mean([b for b, _ in bc]):.2f} | {mean([c for _, c in bc]):.2f} |")
        lines.append("")

    with open(os.path.join(out, "ab_tables.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(out, "ab_pairs.csv"), "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["cell", "compare", "seed", "family", "metric", "diff"])
        w.writerows(rows_csv)
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
